func TestParseStatusDate(t *testing.T) {
	cases := []struct {
		input   string
		wantErr bool
		wantY   int
		wantM   time.Month
		wantD   int
		desc    string
	}{
		// Accepted formats
		{"2026-04-10", false, 2026, time.April, 10, "YYYY-MM-DD"},
		{"04/10/2026", false, 2026, time.April, 10, "MM/DD/YYYY"},
		{"04-10-2026", false, 2026, time.April, 10, "MM-DD-YYYY"},
		{"04/10/26", false, 2026, time.April, 10, "MM/DD/YY"},
		{"04-10-26", false, 2026, time.April, 10, "MM-DD-YY"},

		// Whitespace trimming
		{"  2026-04-10  ", false, 2026, time.April, 10, "YYYY-MM-DD with surrounding spaces"},

		// Additional valid dates
		{"2025-01-22", false, 2025, time.January, 22, "YYYY-MM-DD January"},
		{"01/22/2025", false, 2025, time.January, 22, "MM/DD/YYYY January"},
		{"12/31/2025", false, 2025, time.December, 31, "MM/DD/YYYY December"},

		// Error cases
		{"April 10", true, 0, 0, 0, "long month name (unsupported)"},
		{"", true, 0, 0, 0, "empty string"},
		{"10/04/2026", false, 2026, time.October, 4, "ambiguous MM/DD — treated as October 4, not April 10"},
		{"not-a-date", true, 0, 0, 0, "garbage input"},
		{"2026/04/10", true, 0, 0, 0, "YYYY/MM/DD slash (unsupported)"},
	}

	for _, tc := range cases {
		t.Run(tc.desc, func(t *testing.T) {
			got, err := parseStatusDate(tc.input, "US")
			if tc.wantErr {
				if err == nil {
					t.Errorf("parseStatusDate(%q) = %v, want error", tc.input, got)
				}
				return
			}
			if err != nil {
				t.Fatalf("parseStatusDate(%q) returned error: %v", tc.input, err)
			}
			if got.Year() != tc.wantY || got.Month() != tc.wantM || got.Day() != tc.wantD {
				t.Errorf("parseStatusDate(%q) = %s, want %04d-%02d-%02d",
					tc.input, got.Format("2006-01-02"), tc.wantY, int(tc.wantM), tc.wantD)
			}
		})
	}
}

