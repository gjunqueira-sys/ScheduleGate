func TestAssess_AnonymousSchedule(t *testing.T) {
	// Test assessment of the large anonymous test schedule
	// This is an integration test that validates the full assessment pipeline
	// works with a realistic, large-scale schedule (6000+ tasks)
	
	r := reader.NewScheduleReader("../internal/reader/testdata/test_anonymous_schedule.csv")
	sched, err := r.Read()
	if err != nil {
		t.Fatalf("Read() returned error: %v", err)
	}

	// Verify schedule loaded correctly
	if len(sched.Tasks) == 0 {
		t.Fatal("expected tasks in schedule")
	}

	// Set status date for consistent testing
	sched.DataDate = time.Date(2026, 4, 10, 0, 0, 0, 0, time.UTC)

	// Run assessment
	assessment := dcma.NewDCMAAssessment(nil)
	assessment.Assess(sched)

	// Verify all 14 metrics were assessed
	if len(assessment.Metrics) != 14 {
		t.Errorf("expected 14 metrics, got %d", len(assessment.Metrics))
	}

	// Verify results exist for all metrics
	for _, m := range assessment.Metrics {
		result, ok := assessment.Results[m.Name()]
		if !ok {
			t.Errorf("missing result for metric %s", m.Name())
		}
		// Verify result has required fields
		if result.Name == "" {
			t.Errorf("metric %s has empty name", m.Name())
		}
		if result.Value < 0 || result.Value > 1 {
			t.Errorf("metric %s value out of range [0,1]: %f", m.Name(), result.Value)
		}
	}
}

func TestAssess_AnonymousSchedule_NoIdentifyingReferences(t *testing.T) {
	// Verify the anonymous schedule has no identifying references
	r := reader.NewScheduleReader("../internal/reader/testdata/test_anonymous_schedule.csv")
	sched, err := r.Read()
	if err != nil {
		t.Fatalf("Read() returned error: %v", err)
	}

	// Check all task names and disciplines for identifying strings
	identifyingStrings := []string{"ross", "demat", "grainger"}
	for _, task := range sched.Tasks {
		nameLower := strings.ToLower(task.Name)
		discLower := strings.ToLower(task.Discipline)
		for _, ident := range identifyingStrings {
			if strings.Contains(nameLower, ident) {
				t.Errorf("task %s name contains identifying string %q: %q", task.TaskID, ident, task.Name)
			}
			if strings.Contains(discLower, ident) {
				t.Errorf("task %s discipline contains identifying string %q: %q", task.TaskID, ident, task.Discipline)
			}
		}
	}
}
