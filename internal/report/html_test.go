func TestAppendToCSV_IncludesToolVersion(t *testing.T) {
	assessment := dcma.NewDCMAAssessment([]int{1})
	assessment.Results = map[string]dcma.MetricResult{
		"Logic": {Name: "Logic", Value: 0.02, Threshold: 0.05, Passing: true},
	}

	csvPath := filepath.Join(t.TempDir(), "test.csv")
	err := AppendToCSV(assessment, "test.csv", "Acme", "P-100", "2026-01-15", csvPath)
	if err != nil {
		t.Fatalf("AppendToCSV returned error: %v", err)
	}

	f, err := os.Open(csvPath)
	if err != nil {
		t.Fatalf("opening CSV: %v", err)
	}
	defer f.Close()

	reader := csv.NewReader(f)
	rows, err := reader.ReadAll()
	if err != nil {
		t.Fatalf("reading CSV: %v", err)
	}

	versionCol := -1
	for i, col := range rows[0] {
		if col == "Tool Version" {
			versionCol = i
			break
		}
	}
	if versionCol < 0 {
		t.Fatal("CSV header missing 'Tool Version' column")
	}
	if rows[1][versionCol] != version.Display() {
		t.Fatalf("CSV row Tool Version = %q, want %q", rows[1][versionCol], version.Display())
	}
}

