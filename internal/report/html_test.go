func TestGenerateHTML_WritesCompleteReport(t *testing.T) {
	assessment := dcma.NewDCMAAssessment([]int{1, 4, 10})
	assessment.Results = map[string]dcma.MetricResult{
		"Logic": {
			Name: "Logic", Value: 0.02, Threshold: 0.05, Passing: true,
		},
		"Relationship Types": {
			Name: "Relationship Types", Value: 0.95, Threshold: 0.90, Passing: true,
		},
		"Resources": {
			Name: "Resources", Value: 0, Threshold: 0.95, Passing: true, NotApplicable: true,
		},
	}

	out := filepath.Join(t.TempDir(), "assess_report.html")
	err := GenerateHTML(assessment, "sample.csv", "Acme", "P-100", "2026-01-15", out)
	if err != nil {
		t.Fatalf("GenerateHTML returned error: %v", err)
	}

	raw, err := os.ReadFile(out)
	if err != nil {
		t.Fatalf("reading generated HTML: %v", err)
	}
	html := string(raw)

	if !strings.Contains(html, "</html>") {
		t.Fatal("generated HTML is incomplete: missing closing </html>")
	}
	if !strings.Contains(html, "Threshold:") {
		t.Fatal("generated HTML missing threshold labels")
	}
	if !strings.Contains(html, "≤ 5%") && !strings.Contains(html, "≥ 90%") {
		t.Fatalf("generated HTML missing expected threshold text; got snippet:\n%s", html)
	}
	if !strings.Contains(html, "N/A") {
		t.Fatal("generated HTML missing N/A badge for NotApplicable metric")
	}
}

