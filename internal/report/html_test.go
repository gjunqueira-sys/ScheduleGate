	assessment.Assess(sched)

	// Generate HTML report
	out := filepath.Join(t.TempDir(), "anonymous_report.html")
	statusDate := "2026-04-10"
	err = GenerateHTML(assessment, sched.Name, "Test Customer", "P-TEST", statusDate, out)
	if err != nil {
		t.Fatalf("GenerateHTML returned error: %v", err)
	}

	// Verify HTML file was created and contains expected content
	raw, err := os.ReadFile(out)
	if err != nil {
		t.Fatalf("reading generated HTML: %v", err)
	}
	html := string(raw)

