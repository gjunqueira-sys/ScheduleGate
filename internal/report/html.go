// formatThresholdLabel returns a human-readable threshold string such as "≤ 10%"
// or "≥ 95%", mirroring formatThreshold in excel.go so both reports agree.
func formatThresholdLabel(res dcma.MetricResult) string {
	if res.Threshold == 0.0 {
		return "= 0%"
	}
	if res.Passing && res.Value >= res.Threshold {
		return fmt.Sprintf("≥ %.0f%%", res.Threshold*100)
	}
	if res.Threshold >= 0.90 {
		return fmt.Sprintf("≥ %.0f%%", res.Threshold*100)
	}
	return fmt.Sprintf("≤ %.0f%%", res.Threshold*100)
}

