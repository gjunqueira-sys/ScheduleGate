// GenerateHTML creates an HTML report file.
func GenerateHTML(assessment *dcma.DCMAAssessment, scheduleName, customerName, projectNumber, statusDate, outputPath string) error {
	results := make([]dcma.MetricResult, 0)
	passed := 0

	// Ensure consistent ordering — exclude N/A from pass/total tallying
	metrics := assessment.Metrics
	for _, m := range metrics {
		res := assessment.Results[m.Name()]
		if res.Name != "" && !res.NotApplicable {
			results = append(results, res)
			if res.Passing {
				passed++
			}
		}
	}

	// Creating a view model for the template to allow Description injection
	type MetricViewModel struct {
		dcma.MetricResult
		Description string
	}

	viewResults := make([]MetricViewModel, 0)
	for _, m := range metrics {
		res := assessment.Results[m.Name()]
		viewResults = append(viewResults, MetricViewModel{
			MetricResult: res,
			Description:  m.Description(),
		})
	}

	// Count total applicable metrics (exclude N/A)
	totalApplicable := 0
	for _, m := range metrics {
		res := assessment.Results[m.Name()]
		if !res.NotApplicable {
			totalApplicable++
		}
	}

	data := ReportData{
		ScheduleName:  scheduleName,
		CustomerName:  customerName,
		ProjectNumber: projectNumber,
		StatusDate:    statusDate,
		GeneratedAt:   time.Now().Format("2006-01-02 15:04:05"),
		ToolVersion:   version.Display(),
		OverallScore:  float64(passed) / float64(totalApplicable),
		PassedCount:   passed,
		TotalCount:    totalApplicable,
		Logo:          ui.LogoRaw,
	}

	tmpl, err := template.New("report").Funcs(template.FuncMap{
		"mul":             func(a float64, b int) float64 { return a * float64(b) },
		"formatThreshold": formatThresholdLabel,
	}).Parse(htmlTemplate)

	if err != nil {
		return err
	}

	f, err := os.Create(outputPath)
	if err != nil {
		return err
	}
	defer f.Close()

	// Pass struct with correct type
	return tmpl.Execute(f, struct {
		ScheduleName  string
		CustomerName  string
		ProjectNumber string
		StatusDate    string
		GeneratedAt   string
		ToolVersion   string
		OverallScore  float64
		PassedCount   int
		TotalCount    int
		Results       []MetricViewModel
		Logo          string
	}{
		ScheduleName:  data.ScheduleName,
		CustomerName:  data.CustomerName,
		ProjectNumber: data.ProjectNumber,
		StatusDate:    data.StatusDate,
		GeneratedAt:   data.GeneratedAt,
		ToolVersion:   data.ToolVersion,
		OverallScore:  data.OverallScore,
		PassedCount:   data.PassedCount,
		TotalCount:    data.TotalCount,
		Results:       viewResults,
		Logo:          data.Logo,
	})
}
